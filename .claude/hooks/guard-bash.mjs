#!/usr/bin/env node
// PreToolUse hook (matcher: Bash|PowerShell) — refuses three classes of command that are always a
// mistake in this repository, and lets everything else through untouched.
//
//   1. Recursive force-deletes (`rm -rf`, `Remove-Item -Recurse -Force`) of anything that is not a
//      regenerable build directory inside this repo (`dist`, `node_modules`, `.astro`, `coverage`,
//      `playwright-report`, `test-results`).
//   2. Force-pushes: `git push --force` / `-f` without `--force-with-lease`, and ANY force push
//      whose refspec names `main` (main is PR-only and squash-merged — see CLAUDE.md).
//   3. Writes into a `.env*` file (`>`, `>>`, `tee`, `cp`/`mv` onto it, `Set-Content`/`Out-File`/
//      `Add-Content`). Reading a `.env` is fine; creating or overwriting one from a shell is how
//      secrets end up in a public repo. `.env.example` is exempt — it holds placeholders.
//
// Contract notes (docs/en/hooks.md, verified 2026-09-06):
//   * PreToolUse is a blocking event. Exit 2 blocks the tool call whatever the JSON says.
//   * On exit 2 the message Claude is shown comes from the JSON's blocking decision when there is
//     one, and from stderr otherwise. We print BOTH: the documented
//     `hookSpecificOutput.permissionDecision: "deny"` object on stdout, and the plain reason on
//     stderr so the reason is legible in a terminal and in any client that surfaces stderr.
//   * Anything unrecognised exits 0 — this hook is a guard rail, not an allowlist.
//
// The matching logic is exported so `guard-bash.test.mjs` can exercise it without spawning a shell.
import { readFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

/** Repository root, resolved from this file's own location — never from cwd. */
export const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');

/** Build outputs that are safe to blow away: regenerated by `npm ci` / `npm run build`. */
const DISPOSABLE = [
  'dist',
  'node_modules',
  '.astro',
  'coverage',
  'playwright-report',
  'test-results',
];

/** Split a command line into the individual commands a shell would run. */
function splitCommands(command) {
  return command
    .split(/\r?\n|&&|\|\||[;|]/g)
    .map((s) => s.trim())
    .filter(Boolean);
}

/** Crude but adequate tokeniser: keeps quoted strings together and strips the quotes. */
function tokenize(segment) {
  const out = [];
  const re = /"([^"]*)"|'([^']*)'|(\S+)/g;
  let m;
  while ((m = re.exec(segment)) !== null) out.push(m[1] ?? m[2] ?? m[3]);
  return out;
}

/**
 * True when `target` is a regenerable build directory **of this repository**.
 *
 * The repo qualifier matters: a sibling plan's worktree (`../cct-wt-08/node_modules`) is another
 * session's working copy and must never be deleted from here, even though it ends in a disposable
 * directory name. So a rooted path is first required to resolve inside this repo.
 */
function isDisposable(target) {
  const t = target.replace(/\\/g, '/').replace(/^\.\//, '').replace(/\/+$/, '');
  if (t === '' || t === '.' || t === '..' || t === '~' || t === '/' || /^[A-Za-z]:$/.test(t)) {
    return false;
  }
  // Anything that climbs out of the tree or lives under $HOME is never ours to force-delete.
  if (t.startsWith('..') || t.startsWith('~')) return false;

  const rooted = t.startsWith('/') || /^[A-Za-z]:/.test(t);
  let rel = t;
  if (rooted) {
    // Must resolve inside this repository, and then be judged by its path *within* the repo.
    rel = relative(root, resolve(t)).replace(/\\/g, '/');
    if (rel === '' || rel.startsWith('..')) return false;
  }
  const parts = rel.split('/').filter(Boolean);
  return DISPOSABLE.includes(parts[0]);
}

/** A real `.env` file — the `.example`/`.sample`/`.template` variants hold placeholders, not secrets. */
function isEnvFile(token) {
  const name = (token.replace(/\\/g, '/').split('/').pop() ?? '').toLowerCase();
  if (!/^\.env(\..+)?$/.test(name)) return false;
  return !/\.(example|sample|template|dist)$/.test(name);
}

function checkRecursiveDelete(tokens, segment) {
  const lower = tokens.map((t) => t.toLowerCase());

  // POSIX: rm with both -r and -f, in any order or combined (`-rf`, `-fr`, `-Rf`, `--recursive`).
  if (lower[0] === 'rm' || lower[0] === 'del' || lower[0] === 'erase') {
    const flags = tokens.filter((t) => t.startsWith('-'));
    const joined = flags.join(' ');
    const recursive = /(^|\s)-{1,2}[a-z]*r/i.test(joined) || /--recursive/i.test(joined);
    const force = /(^|\s)-{1,2}[a-z]*f/i.test(joined) || /--force/i.test(joined);
    if (recursive && force) {
      const targets = tokens.slice(1).filter((t) => !t.startsWith('-'));
      if (targets.length === 0 || !targets.every(isDisposable)) {
        return `\`${segment}\` recursively force-deletes something outside this repo's regenerable build directories (${DISPOSABLE.join(', ')}).`;
      }
    }
    return null;
  }

  // PowerShell: Remove-Item / ri / rd with -Recurse and -Force (parameters may be abbreviated).
  if (['remove-item', 'ri', 'rd', 'rmdir'].includes(lower[0])) {
    const joined = lower.join(' ');
    const recursive = /\s-r(e(c(u(r(s(e)?)?)?)?)?)?\b/.test(joined) || /\s-s\b/.test(joined);
    const force = /\s-fo(r(c(e)?)?)?\b/.test(joined) || /\s-f\b/.test(joined);
    if (recursive && force) {
      const targets = tokens
        .slice(1)
        .filter((t) => !t.startsWith('-') && !t.startsWith('$'))
        .filter((t) => t.toLowerCase() !== 'path' && t.toLowerCase() !== 'literalpath');
      if (targets.length === 0 || !targets.every(isDisposable)) {
        return `\`${segment}\` recursively force-deletes something outside this repo's regenerable build directories (${DISPOSABLE.join(', ')}).`;
      }
    }
  }
  return null;
}

function checkForcePush(tokens, segment) {
  const lower = tokens.map((t) => t.toLowerCase());
  if (lower[0] !== 'git' || !lower.includes('push')) return null;

  const lease = lower.some(
    (t) => t.startsWith('--force-with-lease') || t === '--force-if-includes',
  );
  const forced =
    lower.includes('--force') ||
    lower.includes('-f') ||
    lower.some((t) => /^-[a-z]*f[a-z]*$/.test(t) && t !== '-f' && !t.startsWith('--'));
  if (!forced && !lease) return null;

  const targetsMain = lower.some((t) => t === 'main' || t.endsWith(':main') || t.endsWith('/main'));
  if (targetsMain) {
    return `\`${segment}\` force-pushes \`main\`. \`main\` is PR-only and squash-merged; rebase your branch and open a PR instead.`;
  }
  if (forced && !lease) {
    return `\`${segment}\` force-pushes without a lease. Use \`--force-with-lease\` so you cannot silently discard a teammate's commits.`;
  }
  return null;
}

function checkEnvWrite(tokens, segment) {
  const lower = tokens.map((t) => t.toLowerCase());

  // Shell redirection into a .env file: `... > .env`, `... >> .env.local`, `... | tee .env`.
  const redirect = segment.match(/>>?\s*("[^"]*"|'[^']*'|\S+)/);
  if (redirect) {
    const target = redirect[1].replace(/^["']|["']$/g, '');
    if (isEnvFile(target)) {
      return `\`${segment}\` writes into \`${target}\`. Secrets never enter this public repo: use \`.env.local\` (git-ignored), a GitHub secret, or \`.claude/settings.local.json\`.`;
    }
  }

  // `cp`/`mv`/`install` write to their LAST argument only — copying *from* a .env is not a leak
  // into the repo, so only the destination is checked.
  const copiers = ['cp', 'mv', 'install'];
  const streamers = ['tee', 'set-content', 'out-file', 'add-content'];
  if (copiers.includes(lower[0]) || streamers.includes(lower[0]) || lower.includes('tee')) {
    const args = tokens.slice(1).filter((t) => !t.startsWith('-'));
    const candidates = copiers.includes(lower[0]) ? args.slice(-1) : args;
    const target = candidates.find((t) => isEnvFile(t));
    if (target) {
      return `\`${segment}\` writes into \`${target}\`. Secrets never enter this public repo: use \`.env.local\` (git-ignored), a GitHub secret, or \`.claude/settings.local.json\`.`;
    }
  }
  return null;
}

/**
 * Decide whether a shell command may run.
 * @returns {string | null} a human-readable reason to block, or null to allow.
 */
export function assess(command) {
  if (typeof command !== 'string' || command.trim() === '') return null;
  for (const segment of splitCommands(command)) {
    const tokens = tokenize(segment);
    if (tokens.length === 0) continue;
    const reason =
      checkRecursiveDelete(tokens, segment) ??
      checkForcePush(tokens, segment) ??
      checkEnvWrite(tokens, segment);
    if (reason) return reason;
  }
  return null;
}

// --- hook entrypoint (skipped when this file is imported by guard-bash.test.mjs) ---------------
// Compare resolved paths rather than raw strings: on Windows argv[1] is a drive path while
// import.meta.url is a file:// URL, and the drive letter's case is not guaranteed to match.
const invoked = process.argv[1] ? resolve(process.argv[1]).toLowerCase() : '';
const isDirectRun =
  invoked !== '' && resolve(fileURLToPath(import.meta.url)).toLowerCase() === invoked;

if (isDirectRun) {
  let input = {};
  try {
    input = JSON.parse(readFileSync(0, 'utf8') || '{}');
  } catch {
    process.exit(0);
  }
  const tool = input.tool_name ?? '';
  if (tool !== 'Bash' && tool !== 'PowerShell') process.exit(0);

  const reason = assess(input.tool_input?.command ?? '');
  if (!reason) process.exit(0);

  const message = `Blocked by guard-bash: ${reason} (see .claude/hooks/guard-bash.mjs and CLAUDE.md)`;
  console.log(
    JSON.stringify({
      hookSpecificOutput: {
        hookEventName: 'PreToolUse',
        permissionDecision: 'deny',
        permissionDecisionReason: message,
      },
    }),
  );
  // On exit 2 the blocking reason Claude sees comes from stderr when the JSON does not supply one,
  // so print it there too rather than relying on one channel.
  process.stderr.write(`${message}\n`);
  process.exit(2);
}
